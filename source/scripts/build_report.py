def set_paragraph_text(paragraph, text: str) -> None:
    """Replace a paragraph's text, keeping the sample's own run formatting.

    The first run carries the paragraph's visible formatting, so the new text
    goes there and the remaining runs are removed. Fonts, sizes, justification
    and spacing are untouched because they live on the paragraph and the run.
    """
    runs = paragraph.runs
    if not runs:
        paragraph.add_run(text)
        return
    runs[0].text = text
    for run in runs[1:]:
        run._element.getparent().remove(run._element)


def blank_paragraph(paragraph) -> None:
    set_paragraph_text(paragraph, "")


def _page_breaks(paragraph):
    """All page-break elements in a paragraph. `w:br` lives inside `w:r`, so this
    must search descendants rather than direct children."""
    return [b for b in paragraph._p.findall(".//" + qn("w:br"))
            if b.get(qn("w:type")) == "page"]


def fix_chapter_pagination(paragraphs) -> list[str]:
    """Stop the sample's blank pages between chapters.

    The sample forces each chapter onto a new page with a `w:br type="page"`,
    but places it *inside* the empty spacer paragraph that precedes the chapter
    heading rather than at the end of the preceding prose. Word therefore starts
    a page for that spacer, immediately breaks again, and leaves a fully blank
    page in between.

    The break is moved onto the heading itself as `pageBreakBefore`, which keeps
    the intended "every chapter opens a fresh page" layout while removing the
    empty page. The spacer paragraph is left in place so the chapter still opens
    with the breathing room the sample had.
    """
    notes = []
    for index, paragraph in enumerate(paragraphs):
        breaks = _page_breaks(paragraph)
        if not breaks:
            continue
        # Find the next paragraph with visible content: that is the real start of
        # the new section.
        target = next(
            (p for p in paragraphs[index + 1:] if p.text.strip() or p._p.findall(".//" + qn("w:drawing"))),
            None,
        )
        if target is None:
            break
        for b in breaks:
            b.getparent().remove(b)
        target.paragraph_format.page_break_before = True
        notes.append(f"moved break from paragraph {index} onto {target.text.strip()[:46]!r}")
    return notes


def tighten_cover(paragraphs, drop: int = 2) -> int:
    """Reclaim vertical space on the cover so its last line is not orphaned.

    The sample's cover carries five consecutive empty spacer paragraphs between
    the student block and the instructor block. Its final line, the closing
    department line, therefore does not fit and spills onto a page of its own.
    Shortening the longest spacer run by two lines pulls it back onto the cover
    while keeping the block visibly separated.
    """
    cover_end = next(
        (i for i, p in enumerate(paragraphs) if p.paragraph_format.page_break_before),
        len(paragraphs),
    )
    blanks = [
        i for i in range(cover_end)
        if not paragraphs[i].text.strip() and not paragraphs[i]._p.findall(".//" + qn("w:drawing"))
    ]
    runs: list[list[int]] = []
    for index in blanks:
        if runs and index == runs[-1][-1] + 1:
            runs[-1].append(index)
        else:
            runs.append([index])
    if not runs:
        return 0
    longest = max(runs, key=len)
    if len(longest) <= drop:
        return 0
    # Remove from the middle of the run so the space stays balanced either side.
    victims = longest[len(longest) // 2 - drop // 2: len(longest) // 2 - drop // 2 + drop]
    removed = 0
    for index in sorted(victims, reverse=True):
        element = paragraphs[index]._p
        if element.getparent() is not None:
            element.getparent().remove(element)
            removed += 1
    return removed


def drop_orphan_spacers(paragraphs) -> int:
    """Remove blank paragraphs stranded immediately before a forced page break.

    Once a chapter heading carries `pageBreakBefore`, any empty paragraph sitting
    just before it is pushed onto a page of its own: the preceding page fills, the
    blank paragraph spills over, and the heading's break starts another page. The
    blank page is an artefact of the spacer, so the spacer goes; the heading keeps
    its own leading space, which is where the sample's visual gap came from.
    """
    removed = 0
    for index, paragraph in enumerate(paragraphs):
        if not paragraph.paragraph_format.page_break_before:
            continue
        previous = index - 1
        while previous >= 0:
            candidate = paragraphs[previous]
            if candidate.text.strip() or candidate._p.findall(".//" + qn("w:drawing")):
                break
            if candidate._p.getparent() is None:
                previous -= 1
                continue
            candidate._p.getparent().remove(candidate._p)
            removed += 1
            previous -= 1
    return removed


def trim_trailing_blanks(doc) -> int:
    """Drop trailing empty paragraphs that would otherwise spill onto a blank page.

    Only paragraphs that carry no text, no drawing and no page break are removed,
    and the body always keeps one, because Word requires a final paragraph.
    """
    body = doc.element.body
    removed = 0
    while True:
        children = [c for c in body if c.tag == qn("w:p")]
        if len(children) <= 1:
            break
        last = children[-1]
        has_text = "".join(last.itertext()).strip()
        has_drawing = last.findall(".//" + qn("w:drawing"))
        has_break = any(b.get(qn("w:type")) == "page" for b in last.findall(".//" + qn("w:br")))
        if has_text or has_drawing or has_break:
            break
        parent = last.getparent()
        if parent is None:
            break
        parent.remove(last)
        removed += 1
    return removed


def write_block(paragraphs, start_index: int, lines: list[str]) -> int:
    """Write `lines` into consecutive paragraphs from `start_index`.

    Returns the index just past the last paragraph written, so callers can insert
    further paragraphs when the replacement is longer than the original block.
    """
    end = start_index + len(lines)
    for offset, line in enumerate(lines):
        set_paragraph_text(paragraphs[start_index + offset], line)
    return end


def blank_remainder(paragraphs, start_index: int, end_index: int) -> None:
    for index in range(start_index, end_index):
        blank_paragraph(paragraphs[index])


def insert_code_paragraphs(paragraphs, anchor_index: int, lines: list[str], style_from) -> None:
    """Insert code paragraphs before `anchor_index`, copying the sample's code formatting."""
    for line in lines:
        paragraph = paragraphs[anchor_index].insert_paragraph_before("")
        template = style_from()
        # Copy the paragraph properties (spacing, indentation) and the run
        # properties (Consolas, 8pt, no spacing) from a real code paragraph.
        if template._p.pPr is not None:
            existing = paragraph._p.find(qn("w:pPr"))
            if existing is not None:
                paragraph._p.remove(existing)
            paragraph._p.insert(0, copy.deepcopy(template._p.pPr))
        run = paragraph.add_run(line)
        if template.runs and template.runs[0]._element.rPr is not None:
            run._element.insert(0, copy.deepcopy(template.runs[0]._element.rPr))


def check_figure_sources() -> None:
    """Fail early if a figure is missing, so the report is never built with a gap."""
    missing = [name for name in FIGURE_MAP.values() if not (FIGURES / name).exists()]
    if missing:
        raise SystemExit(
            "Missing report figures: " + ", ".join(missing) +
            "\nRun `npm run capture:report` with the backend and frontend running."
        )


def swap_figures(doc) -> None:
    """Replace the sample's screenshot parts with the fresh captures.

    The extents are not touched: every sample content figure is already 1440x900,
    1024x768 or 390x844, which is exactly what the capture script produces, so the
    aspect ratio matches by construction. The script asserts that anyway.
    """
